# wconn_gen.py -- emit the window-W connectivity automaton (wconn.py) as a C table.
#   W = 2: w2conn_auto.h in the format of c6idea/src/w2_auto.h (W2_NSTATE, W2_INIT, w2_trans[s][kind][N][S], w2_close[...]),
#          S index 0 -> 0, 1 -> 1, 2 -> uncertain (= 0, by monotonicity); kind 0 = step from i = 0 (S must be 0).
#   W = 3: w3conn_auto.h: W3_NSTATE, W3_INIT, w3_trans[s][N][S][T], w3_close[s][N][S][T] (uncertain passed as 0).
# usage: python3 -I wconn_gen.py W OUT
import sys, os, itertools
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import wconn as C
W = int(sys.argv[1]); out = sys.argv[2]
st0 = C.start(); states = [st0]; index = {st0: 0}; q = [st0]
while q:
    s = q.pop(0)
    for a in itertools.product((0, 1), repeat=W):
        ns = C.step(s, a, W)
        if ns is not None and ns not in index: index[ns] = len(states); states.append(ns); q.append(ns)
NS = len(states)
def tr(s, a):
    ns = C.step(s, a, W); return -1 if ns is None else index[ns]
with open(out, 'w') as f:
    f.write('/* generated by wconn_gen.py (window-%d connectivity + local degree automaton, wconn.py); do not edit */\n' % W)
    for n, s in enumerate(states): f.write('/* %3d: part=%s cnt=%s u=%d */\n' % (n, s[0], s[1], s[2]))
    if W == 2:
        f.write('#define W2_NSTATE %d\n#define W2_INIT 0\n' % NS)
        f.write('static const int w2_trans[W2_NSTATE][3][2][3] = {\n')
        for s in states:
            rows = []
            for kind in range(3):
                rows.append('{' + ', '.join('{' + ', '.join(str(-2 if (kind == 0 and si != 0) else tr(s, (N, 1 if si == 1 else 0))) for si in range(3)) + '}' for N in range(2)) + '}')
            f.write('  {' + ', '.join(rows) + '},\n')
        f.write('};\nstatic const double w2_close[W2_NSTATE][3][2][3] = {\n')
        for s in states:
            rows = []
            for kind in range(3):
                rows.append('{' + ', '.join('{' + ', '.join(repr(-1.0 if kind == 0 else float(C.close_value(s, (N, 1 if si == 1 else 0), W))) for si in range(3)) + '}' for N in range(2)) + '}')
            f.write('  {' + ', '.join(rows) + '},\n')
        f.write('};\n')
    elif W == 3:
        f.write('#define W3_NSTATE %d\n#define W3_INIT 0\n' % NS)
        f.write('static const short w3_trans[W3_NSTATE][2][2][2] = {\n')
        for s in states:
            f.write('  {' + ', '.join('{' + ', '.join('{' + ', '.join(str(tr(s, (N, S, T))) for T in range(2)) + '}' for S in range(2)) + '}' for N in range(2)) + '},\n')
        f.write('};\nstatic const double w3_close[W3_NSTATE][2][2][2] = {\n')
        for s in states:
            f.write('  {' + ', '.join('{' + ', '.join('{' + ', '.join(repr(float(C.close_value(s, (N, S, T), W))) for T in range(2)) + '}' for S in range(2)) + '}' for N in range(2)) + '},\n')
        f.write('};\n')
print("W=%d states %d -> %s" % (W, NS, out))
